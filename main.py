# ── In-container RAG store (ChromaDB) ──────────────────────────────────────────
# Self-contained RAG: uploaded files are chunked, embedded, and stored locally.
# The /chat endpoint retrieves relevant chunks and injects them as LLM context.
_rag_collection = None
_rag_ready = False

def _init_rag_store():
    """Initialize ChromaDB collection for in-container RAG."""
    global _rag_collection, _rag_ready
    try:
        import chromadb
        client = chromadb.Client()  # ephemeral in-memory store
        _rag_collection = client.get_or_create_collection(
            name="agent_knowledge",
            metadata={"hnsw:space": "cosine"},
        )
        _rag_ready = True
        logger.info("ChromaDB RAG store initialized (in-memory)")
    except ImportError:
        logger.warning("chromadb not installed — RAG disabled. Add 'chromadb' to requirements.txt.")
    except Exception as e:
        logger.warning("ChromaDB init failed (non-fatal): %s", e)

# NOTE: _init_rag_store() is called inside the background loader thread,
# NOT at module top-level — prevents import-time crashes from blocking uvicorn.


def _chunk_text(text: str, chunk_size: int = 500, overlap: int = 50) -> List[str]:
    """Split text into overlapping chunks for RAG ingestion."""
    chunks = []
    start = 0
    text = text.strip()
    while start < len(text):
        end = start + chunk_size
        chunk = text[start:end].strip()
        if chunk:
            chunks.append(chunk)
        start += chunk_size - overlap
    return chunks


def _extract_text_from_file(file_bytes: bytes, filename: str) -> str:
    """Extract plain text from uploaded file (PDF, TXT, etc.)."""
    ext = filename.rsplit(".", 1)[-1].lower() if "." in filename else ""
    if ext == "pdf":
        try:
            import pdfplumber
            import io
            with pdfplumber.open(io.BytesIO(file_bytes)) as pdf:
                pages = [page.extract_text() or "" for page in pdf.pages]
            return "\n\n".join(p.strip() for p in pages if p.strip())
        except ImportError:
            logger.warning("pdfplumber not installed — cannot parse PDF")
            return ""
        except Exception as e:
            logger.warning("PDF extraction failed: %s", e)
            return ""
    # Plain text files
    try:
        return file_bytes.decode("utf-8", errors="replace")
    except Exception:
        return ""


def _ingest_to_rag(text: str, source: str = "upload") -> int:
    """Chunk text and add to ChromaDB collection. Returns number of chunks added."""
    if not _rag_ready or not _rag_collection:
        return 0
    chunks = _chunk_text(text)
    if not chunks:
        return 0
    ids = [hashlib.md5(f"{source}:{i}:{c[:50]}".encode()).hexdigest() for i, c in enumerate(chunks)]
    metadatas = [{"source": source, "chunk_index": i} for i in range(len(chunks))]
    _rag_collection.upsert(documents=chunks, ids=ids, metadatas=metadatas)
    logger.info("Ingested %d chunks from %s into ChromaDB", len(chunks), source)
    return len(chunks)


def _query_rag(query: str, top_k: int = 5) -> str:
    """Query ChromaDB for relevant chunks and return formatted context."""
    if not _rag_ready or not _rag_collection:
        return ""
    try:
        count = _rag_collection.count()
        if count == 0:
            return ""
        results = _rag_collection.query(
            query_texts=[query],
            n_results=min(top_k, count),
        )
        docs = results.get("documents", [[]])[0]
        if not docs:
            return ""
        context_parts = []
        for i, doc in enumerate(docs, 1):
            context_parts.append(f"[{i}] {doc}")
        return (
            "\n\n=== KNOWLEDGE BASE CONTEXT ===\n"
            "The following information was retrieved from the uploaded documents. "
            "Use this context to answer the user's question accurately.\n\n"
            + "\n\n---\n\n".join(context_parts)
            + "\n=== END OF KNOWLEDGE BASE CONTEXT ===\n"
        )
    except Exception as e:
        logger.warning("RAG query failed: %s", e)
        return ""



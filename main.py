def _call_gemini_fallback(message: str) -> str:
    """Call Gemini when the agent module is unavailable or returns nothing useful."""
    prompt = f"{_agent_sys_prompt}\n\nUser: {message}"
    _vertex_error = None  # Persist across except blocks (Python 3 deletes exception vars)

    # 1. Try Vertex AI (uses ADC — always available in Cloud Run)
    try:
        import vertexai
        from vertexai.generative_models import GenerativeModel
        project = (
            os.environ.get("GOOGLE_CLOUD_PROJECT")
            or os.environ.get("PROJECT_ID", "gen-ai-poc-onboarding")
        )
        location = os.environ.get("GOOGLE_CLOUD_REGION", "us-central1")
        vertexai.init(project=project, location=location)
        model = GenerativeModel("gemini-2.5-flash")
        response = model.generate_content(prompt)
        return response.text
    except Exception as vertex_err:
        _vertex_error = vertex_err
        logger.warning("Vertex AI fallback failed: %s", vertex_err)

    # 2. Try google.generativeai with API key
    try:
        import google.generativeai as genai  # type: ignore
        api_key = os.environ.get("GOOGLE_API_KEY") or os.environ.get("GEMINI_API_KEY")
        if not api_key:
            raise ValueError("GOOGLE_API_KEY / GEMINI_API_KEY not set")
        genai.configure(api_key=api_key)
        model = genai.GenerativeModel("gemini-2.5-flash")
        response = model.generate_content(prompt)
        return response.text
    except Exception as genai_err:
        logger.error("All LLM fallbacks exhausted — Vertex: %s | Gemini: %s", _vertex_error, genai_err)
        return f"Hello! I am validation-check. I received your message but my AI backend is not reachable right now."


# ── KRE backend proxy ──────────────────────────────────────────────
# When KRE_BACKEND_URL + KRE_AGENT_ID env vars are set (injected at deploy time),
# /chat proxies to the KRE platform backend which has full context:
#   - Firestore agent config (system prompt, training history)
#   - ChromaDB RAG knowledge base
#   - MCP server credentials + function-calling
_KRE_BACKEND_URL = os.environ.get("KRE_BACKEND_URL", "").rstrip("/")
_KRE_AGENT_ID    = os.environ.get("KRE_AGENT_ID", "")


def _call_kre_backend(message: str) -> Optional[str]:
    """Proxy the chat message to the KRE backend (full context: Firestore/RAG/MCP)."""
    if not (_KRE_BACKEND_URL and _KRE_AGENT_ID):
        return None
    # Use /api/proxy/agent-chat (no Firebase auth needed — same endpoint the sandbox uses)
    endpoint = f"{_KRE_BACKEND_URL}/api/proxy/agent-chat/{_KRE_AGENT_ID}"
    try:
        import urllib.request as _req
        payload = json.dumps({"message": message, "session_id": None}).encode()
        http_req = _req.Request(
            endpoint,
            data=payload,
            headers={"Content-Type": "application/json", "User-Agent": "KRE-CloudRun-Proxy/1.0"},
            method="POST",
        )
        with _req.urlopen(http_req, timeout=60) as resp:
            body = json.loads(resp.read().decode())
            # /api/proxy/agent-chat returns {status, body, latency_ms}
            # body.response comes from chat_with_agent(); body.answer from run_agent()
            inner = body.get("body") or body
            text = None
            if isinstance(inner, dict):
                text = inner.get("response") or inner.get("answer")
            if not text:
                text = body.get("response") or body.get("answer")
            if text and isinstance(text, str) and text.strip():
                logger.info("KRE backend proxy succeeded (agent=%s)", _KRE_AGENT_ID)
                return text.strip()
    except Exception as proxy_err:
        logger.warning("KRE backend proxy failed (%s): %s", endpoint, proxy_err)
    return None



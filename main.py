def _load_agent() -> None:
    """Load agent module — designed to run in a background thread so the web
    server can start immediately and respond to /health startup probes."""
    global _agent_instance, _agent_sys_prompt, _agent_loading, _agent_load_error
    _load_start = time.monotonic()
    try:
        project_root = os.path.dirname(os.path.abspath(__file__))
        if project_root not in sys.path:
            sys.path.insert(0, project_root)
        module_path = os.path.join(project_root, _agent_module_path.replace("/", os.sep))
        if not os.path.exists(module_path):
            _agent_load_error = f"Agent module not found: {_agent_module_path}"
            logger.error("CRITICAL: %s not found at %s", _agent_module_path, module_path)
            return
        try:
            spec = importlib.util.spec_from_file_location("agent_module", module_path)
            mod = importlib.util.module_from_spec(spec)
            spec.loader.exec_module(mod)  # type: ignore[union-attr]
            logger.info("%s loaded successfully (%.1fs)", _agent_module_path, time.monotonic() - _load_start)
        except Exception as exc:
            _agent_load_error = f"Module import failed: {exc}"
            logger.error(
                "CRITICAL: %s failed to load - %s\n%s",
                _agent_module_path,
                exc,
                traceback.format_exc(),
            )
            return

        # Discover agent class: prefer "Agent", then any class defined in this module
        preferred_names = {"Agent", "Bot", "Assistant"}
        candidates: List[tuple] = []
        for name in preferred_names:
            cls = getattr(mod, name, None)
            if cls is not None and isinstance(cls, type):
                candidates.insert(0, (name, cls))
        for name in dir(mod):
            if name.startswith("_"):
                continue
            cls = getattr(mod, name, None)
            if cls is None or not isinstance(cls, type):
                continue
            if getattr(cls, "__module__", None) not in ("agent_module", None):
                continue
            if any(c[0] == name for c in candidates):
                continue
            candidates.append((name, cls))

        for cls_name, cls in candidates:
            try:
                instance = cls()
                _agent_instance = instance
                # Extract system_prompt from the instance if available
                for attr in ("system_prompt", "_system_prompt"):
                    val = getattr(instance, attr, None)
                    if val and isinstance(val, str):
                        _agent_sys_prompt = val
                        break
                cfg = getattr(instance, "config", None)
                if cfg and isinstance(cfg, dict):
                    sp = cfg.get("system_prompt")
                    if sp:
                        _agent_sys_prompt = sp
                logger.info("Agent class '%s' instantiated successfully (%.1fs total)", cls_name, time.monotonic() - _load_start)
                return
            except Exception as exc:
                logger.warning("Could not instantiate '%s': %s", cls_name, exc)

        _agent_load_error = "No agent class could be instantiated"
        logger.error("No agent class could be instantiated from %s", _agent_module_path)
    finally:
        _agent_loading = False
        logger.info("Agent loading completed in %.1fs (loaded=%s)", time.monotonic() - _load_start, _agent_instance is not None)
        # Initialize RAG store AFTER agent loading (still in background thread)
        _init_rag_store()



def _looks_like_error_response(text: Optional[str]) -> bool:
    if not text:
        return True
    normalized = text.strip().lower()
    error_prefixes = (
        "error:",
        "failed",
        "exception",
        "traceback",
        "internal server error",
    )
    return normalized.startswith(error_prefixes)



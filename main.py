@app.post("/upload")
async def upload_file(file: UploadFile = File(...)):
    """Upload a document to the agent's knowledge base.

    Accepts PDF, TXT, MD, CSV, and other text files.
    The file is chunked and stored in ChromaDB for RAG retrieval.
    """
    if not _rag_ready:
        raise HTTPException(status_code=503, detail="RAG store not available. Ensure chromadb is in requirements.txt.")
    try:
        file_bytes = await file.read()
        if not file_bytes:
            raise HTTPException(status_code=400, detail="Empty file")
        text = _extract_text_from_file(file_bytes, file.filename or "unknown.txt")
        if not text.strip():
            raise HTTPException(status_code=400, detail="Could not extract text from file")
        chunks_added = _ingest_to_rag(text, source=file.filename or "upload")
        total_docs = _rag_collection.count() if _rag_collection else 0
        return {
            "status": "success",
            "filename": file.filename,
            "chunks_added": chunks_added,
            "total_chunks_in_knowledge_base": total_docs,
            "message": f"Successfully ingested {chunks_added} chunks from {file.filename}",
        }
    except HTTPException:
        raise
    except Exception as exc:
        logger.error("File upload error: %s", exc)
        raise HTTPException(status_code=500, detail=str(exc))


@app.post("/chat")
async def chat(request: ChatRequest):
    """Route a chat message to the agent and return a response.

    Priority order:
      1. Local RAG context  — retrieves relevant chunks from uploaded documents
      2. KRE backend proxy  — full Firestore/RAG/MCP context
      3. Local agent module — in-container class/method invocation
      4. Vertex AI / Gemini — bare LLM with system prompt + RAG context
    """
    try:
        agent_response: Optional[str] = None

        # ── 0. Retrieve local RAG context from uploaded documents ─────────────
        local_rag_context = _query_rag(request.message, top_k=5)

        # ── 1. KRE backend proxy (has full Firestore/RAG/MCP context) ────────
        # When deployed by the KRE platform, KRE_AGENT_ID and KRE_BACKEND_URL are
        # injected as env vars. However, if we have LOCAL RAG context from
        # direct uploads, we skip the proxy and answer with local context + Gemini
        # because the KRE backend doesn't know about files uploaded directly to
        # this container.
        if not local_rag_context:
            kre_response = _call_kre_backend(request.message)
            if kre_response:
                return ChatResponse(response=kre_response)

        if _agent_instance is not None:
            # ── 1. Named methods: run / generate_response / process / execute / chat ──
            for method_name in ("run", "generate_response", "process", "execute", "chat"):
                method = getattr(_agent_instance, method_name, None)
                if not (method and callable(method)):
                    continue
                try:
                    result = method(request.message)
                    if isinstance(result, dict):
                        agent_response = (
                            result.get("response")
                            or result.get("result")
                            or result.get("answer")
                            or result.get("output")
                        )
                        if agent_response is None:
                            agent_response = str(result)
                    elif result is not None:
                        agent_response = str(result)
                    if agent_response and _looks_like_error_response(agent_response):
                        logger.warning("Agent returned error-like output via %s.%s(); using fallback", type(_agent_instance).__name__, method_name)
                        agent_response = None
                    if agent_response:
                        logger.info("Response via %s.%s()", type(_agent_instance).__name__, method_name)
                        break
                except Exception as exc:
                    logger.warning("%s.%s() failed: %s", type(_agent_instance).__name__, method_name, exc)

            # ── 2. __call__ — try multiple input formats ──────────────────────
            if not agent_response and callable(_agent_instance):
                call_formats = [
                    request.message,
                    {"message": request.message, "context": request.context},
                    {"handler": "chat", "params": {"message": request.message}},
                    {"handler": "process", "params": {"text": request.message, "query": request.message}},
                ]
                for fmt in call_formats:
                    try:
                        result = _agent_instance(fmt)
                        if isinstance(result, dict):
                            # Skip if agent returned an error for this format
                            if result.get("status") == "error" and isinstance(fmt, dict) and "handler" in fmt:
                                continue
                            agent_response = (
                                result.get("response")
                                or result.get("result")
                                or result.get("answer")
                                or result.get("output")
                            )
                            if agent_response is None:
                                agent_response = str(result)
                        elif result is not None:
                            agent_response = str(result)
                        if agent_response and _looks_like_error_response(agent_response):
                            logger.warning("Agent returned error-like output via __call__; using fallback")
                            agent_response = None
                        if agent_response:
                            logger.info("Response via __call__ (format=%s)", type(fmt).__name__)
                            break
                    except Exception as exc:
                        logger.debug("__call__ with %s failed: %s", type(fmt).__name__, exc)

        # ── 3. Fallback: real Gemini call with RAG context ─────────────────────
        if not agent_response:
            if local_rag_context:
                # Inject RAG context into the Gemini prompt so uploaded docs are used
                rag_augmented_message = (
                    f"{local_rag_context}\n\nUser question: {request.message}\n\n"
                    "Answer the user's question based on the knowledge base context above. "
                    "If the answer is in the context, provide it accurately. "
                    "If the context doesn't contain the answer, say so."
                )
                logger.info("Using Gemini fallback with %d chars of RAG context", len(local_rag_context))
                agent_response = _call_gemini_fallback(rag_augmented_message)
            else:
                logger.warning(
                    "Agent did not produce a response (loaded=%s) — using Gemini fallback",
                    _agent_instance is not None,
                )
                agent_response = _call_gemini_fallback(request.message)

        return ChatResponse(response=agent_response)

    except Exception as exc:
        logger.error("Chat handler error: %s\n%s", exc, traceback.format_exc())
        raise HTTPException(status_code=500, detail=str(exc))


